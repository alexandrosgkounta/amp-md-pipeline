"""Intrinsic amide exchange rates, NH -> ND in D2O (Bai et al. 1993 Proteins 17:75; reference rates and activation
energies as in the Englander group spreadsheet, Nguyen et al. 2018 JASMS 29:1936). k in s^-1."""
import numpy as np
T = {"A": (0.00, 0.00, 0.00, 0.00), "R": (-0.59, -0.32, 0.08, 0.22), "N": (-0.58, -0.13, 0.49, 0.32), "C": (-0.54, -0.46, 0.62, 0.55),
     "G": (-0.22, 0.22, 0.27, 0.17), "Q": (-0.47, -0.27, 0.06, 0.20), "I": (-0.91, -0.59, -0.73, -0.23), "L": (-0.57, -0.13, -0.58, -0.21),
     "K": (-0.56, -0.29, -0.04, 0.12), "M": (-0.64, -0.28, -0.01, 0.11), "F": (-0.52, -0.43, -0.24, 0.06), "P": (None, -0.19, None, -0.24),
     "S": (-0.44, -0.39, 0.37, 0.30), "T": (-0.79, -0.47, -0.07, 0.20), "W": (-0.40, -0.44, -0.41, -0.11), "Y": (-0.41, -0.37, -0.27, 0.05),
     "V": (-0.74, -0.30, -0.70, -0.14), "D": (0.90, 0.58, -0.30, -0.18), "E": (-0.90, 0.31, -0.51, -0.15), "H": (-0.80, -0.51, 0.80, 0.83)}
NT_RHO = (-1.32, 1.62)
def kch(seq, pD=6.0, T_K=278.15):
    R = 1.987e-3; f = lambda E: np.exp(-E / R * (1 / T_K - 1 / 293.0))
    ka, kb, kw = 10 ** 1.62 / 60 * f(14.0), 10 ** 10.18 / 60 * f(17.0), 10 ** -1.5 / 60 * f(19.0)
    D, OD = 10 ** -pD, 10 ** (pD - 15.05)
    k = np.full(len(seq), np.nan)
    for i in range(1, len(seq)):
        if seq[i] == "P": continue
        la, _, lb, _ = T[seq[i]]; _, ra, _, rb = T[seq[i - 1]]
        if i == 1: ra += NT_RHO[0]; rb += NT_RHO[1]
        k[i] = ka * 10 ** (la + ra) * D + kb * 10 ** (lb + rb) * OD + kw * 10 ** (lb + rb)
    return k
